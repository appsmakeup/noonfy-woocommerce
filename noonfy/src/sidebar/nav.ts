type Row = [key: string, label: string, path: string, icon?: string, sub?: boolean, badge?: string];
const group = (label: string, rows: Row[]): NavGroup => ({
  label,
  items: rows.map(([key, lbl, path, icon, sub, badge]) => ({ key, label: lbl, href: toHref(path), icon: icon || undefined, sub, badge })),
});

